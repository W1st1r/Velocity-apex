import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('public/index.html');
const base=read('public/css/style.css');
const unified=read('public/css/unified-blue-v66.css');
const race=read('public/css/race-control-v65.css');
const menu=read('public/js/main-menu-ui.js');
const manifest=JSON.parse(read('public/manifest.webmanifest'));
const cssFiles=['style.css','mobile-ui.css','owner-panel.css','admin-system.css','payments.css','referrals.css','crews.css'];
assert.match(html,/<title>Velocity Apex · V66<\/title>/);
assert.match(html,/SEASON V66/);
assert.match(html,/css\/unified-blue-v66\.css\?v=20261013-v66-1/);
assert.ok(html.indexOf('race-control-v65.css')<html.indexOf('unified-blue-v66.css'),'unified CSS must be loaded last');
for(const file of cssFiles){
 assert.match(html,new RegExp('css/'+file.replace('.','\\.')+'\\?[^" ]+&theme=v66'),`CSS cache bust missing: ${file}`);
 const css=read('public/css/'+file);
 assert.ok(css.length>1000,`Stylesheet truncated: ${file}`);
}
assert.match(base,/--accent:\s*#55c8ff/);
assert.match(unified,/--va-blue:#58c7ff/);
assert.match(race,/race-control-shell/);
assert.match(unified,/safe-area-inset-top/);
assert.match(unified,/orientation:landscape/);
assert.match(unified,/upgrade-wheel\s*\{\s*background:conic-gradient\(from 0deg,#4bd26e 0 var\(--upgrade-chance\),#e34a5b/);
assert.match(base,/\.free-admin-badge\.admin-helper,.online-admin-prefix\.admin-helper\{--admin-bg:#0e7c76/,'admin rank meanings retained');
assert.match(unified,/#crewDialog/);
assert.equal(manifest.background_color,'#071426');
assert.equal(manifest.theme_color,'#071426');
assert.match(menu,/MutationObserver/);
assert.match(menu,/12000/);
assert.doesNotMatch(menu,/setInterval\(refresh,1400\)/);
const allIDs=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(new Set(allIDs).size,allIDs.length,'duplicate DOM IDs break event handlers');
const screens=['rotate','authGate','menu','referrals','topup','account','promo','friends','freeServers','localMode','career','online','setup','shop','garage','settings','rootAuth','rootConsole','rootConfirm','supportOverlay','staffAdminOverlay','pause','onlineFinish','finish'];
for(const id of screens)assert.ok(allIDs.includes(id),`screen missing ${id}`);
for(const id of ['menuRailPlay','garageBtn','shopBtn','onlineBtn','playBtn','garageTabs','upgradeConfirmStart','upgradeHistoryClose','topupBtn','rootAccountSearch','freeChatInput'])assert.ok(allIDs.includes(id),`interactive element missing ${id}`);
for(const id of ['freeContextAction','freeChatInput','rootAccountSearch','ownerMediaUsername','ownerMediaNote','rootBlockedSearch'])assert.match(html,new RegExp('id="'+id+'" aria-label="[^"]+"'));
console.log('unified_blue_v66_test: OK — 24 overlays, unique IDs, design tokens, accessible controls, cache versioning, semantic Upgrade sectors');
