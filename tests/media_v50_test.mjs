import fs from 'node:fs';
import assert from 'node:assert/strict';
const worker=fs.readFileSync('src/worker.mjs','utf8');
const media=fs.readFileSync('src/media.mjs','utf8');
const online=fs.readFileSync('public/js/online.js','utf8');
const free=fs.readFileSync('public/js/freeroam.js','utf8');
const html=fs.readFileSync('public/index.html','utf8');
for(const token of ['media_events','media_event_payout','/api/media/events/create','applyAccountTransaction','media_event_settlement','media_event_refund']) assert.ok(media.includes(token),'media backend missing '+token);
assert.ok(media.includes("AND ${receiptSql}"),'media event terminal state must share the economy receipt transaction');
assert.ok(media.includes("requestId='media-create-'" )&&media.includes("IDEMPOTENCY_KEY_REQUIRED"),'media event creation must require an idempotency key');
assert.ok(online.includes('mediaCreateRequestId(body)')&&online.includes('clearMediaCreateRequest(body.requestId)'),'media create retries must reuse and then clear the request key');
for(const token of ["this.room.mode==='freeroam'&&this.room.mediaEvent.id===event.id","this.room.mode==='media_race'&&this.room.mediaEvent.id===event.id"])assert.ok(worker.includes(token),'Durable Object media creation must replay the same event safely');
for(const token of ['media_start','media_ready','media_shuffle','mediaEvent']) assert.ok(worker.includes(token),'worker missing '+token);
for(const token of ['onlineMediaCreateBtn','doMediaCreate','joinMediaEvent']) assert.ok(online.includes(token),'online UI missing '+token);
for(const token of ['freeMediaControl','spectatorTarget','media_event_result']) assert.ok(free.includes(token),'free roam media UI missing '+token);
assert.ok(html.includes('data-root-tab="media"'));
assert.ok(fs.existsSync('migrations/0016_media_events.sql'));
console.log('MEDIA V50 static integration: OK');
